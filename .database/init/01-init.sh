#!/bin/bash
set -e

export PGPASSWORD=$POSTGRES_PASSWORD;
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE USER $APP_DATABASE_USER WITH PASSWORD '$APP_DATABASE_PASSWORD';
    CREATE USER $BUSINESS_DATABASE_USER WITH PASSWORD '$BUSINESS_DATABASE_PASSWORD';

    CREATE DATABASE $APP_DATABASE_NAME OWNER $APP_DATABASE_USER;
    CREATE DATABASE $BUSINESS_DATABASE_NAME;
    GRANT CONNECT ON DATABASE $BUSINESS_DATABASE_NAME TO $BUSINESS_DATABASE_USER;
EOSQL